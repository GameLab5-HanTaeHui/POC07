namespace KEY
{
    /// <summary>
    /// 열쇠 무기 타입 열거형.
    ///
    /// ────────────────────────────────────────────────────
    /// [열쇠 추가 방법]
    ///   1. 이 enum 에 항목 추가
    ///   2. KeyDataSO 에셋 생성 후 keyType 설정
    ///   3. PlayerWeaponBase 상속 구현체 작성
    ///   4. WeaponKeyController._weaponMap 에 등록
    /// ────────────────────────────────────────────────────
    /// </summary>
    public enum KeyType
    {
        /// <summary>
        /// 녹슨 열쇠 — 기본 근접형.
        /// 빠른 3단 콤보 + 공중 내리찍기.
        /// </summary>
        Rusty,

        /// <summary>
        /// 갈고리 열쇠 — 훅 액션형.
        /// 적 자물쇠에 걸어 끌어당기거나 플레이어가 이동.
        /// </summary>
        Hook,

        /// <summary>
        /// 태엽 열쇠 — 회전 광역형.
        /// 회전하며 다수 자물쇠를 동시 해제.
        /// </summary>
        Spring,

        /// <summary>
        /// 분열 열쇠 — 투사체형.
        /// 충돌 시 여러 개로 분열.
        /// </summary>
        Split,

        /// <summary>
        /// 공명 열쇠 — 광역 연쇄형.
        /// 해제된 자물쇠 근처에서 추가 반응 발생.
        /// </summary>
        Resonance,

        /// <summary>
        /// 중력 열쇠 — 변형형.
        /// 자물쇠 방향을 뒤집는다.
        /// </summary>
        Gravity,
    }
}