// ============================================================
// SealType.cs  v1.0
// 봉인 타입 열거형 정의
//
// [역할]
//   플레이어가 봉인 열쇠로 적에게 걸 수 있는 봉인 종류를 정의.
//   SealDataSO, EnemySealComponent, EnemyAI 에서 공통 사용.
//
// [봉인 vs 해제]
//   기존 열쇠(RustyKey 등) = 적의 자물쇠를 "열어" 약점 노출
//   봉인 열쇠(SealKey)     = 적에게 자물쇠를 "걸어" 행동 제한
//   → 이 세계관의 열쇠 시스템 쌍방향 구조를 완성
//
// [새 봉인 타입 추가 방법]
//   1. 이 enum 에 항목 추가
//   2. EnemySealComponent.ApplySeal() switch 에 케이스 추가
//   3. EnemyAI.IsSealedAction() switch 에 케이스 추가
//   4. SealDataSO 에셋에서 sealType 설정
//
// [EnemyAI 연동 구조]
//   EnemyAI 는 각 행동 실행 직전에
//   EnemySealComponent.IsSealedAction(SealType) 을 체크.
//   true 이면 해당 행동을 스킵하고 대기 상태 유지.
//
// [네임스페이스]
//   namespace : KEY
// ============================================================

namespace KEY
{
    /// <summary>
    /// 봉인 열쇠가 적에게 걸 수 있는 봉인 종류. (v1.0)
    ///
    /// ────────────────────────────────────────────────────
    /// [전략적 사용 예시]
    ///   기사형 적
    ///     → Guard 봉인: 방패 내리기 → 정면 공략 가능
    ///     → Dash 봉인: 돌진 차단 → 안전하게 자물쇠 해제
    ///
    ///   드론형 적 (추후)
    ///     → Jump 봉인: 상승 차단 → 지상 고정
    ///     → Ranged 봉인: 원거리 공격 차단 → 근접 전투 유도
    ///
    ///   골렘형 적 (추후)
    ///     → All 봉인: 전체 행동 정지 → 자물쇠 해제 시간 확보
    /// ────────────────────────────────────────────────────
    /// </summary>
    public enum SealType
    {
        /// <summary>
        /// 돌진 봉인.
        /// 적의 Dash / 돌진형 이동 행동을 차단.
        /// EnemyAI 의 OnEnterDash() 또는 DashRoutine() 직전에 체크.
        ///
        /// [적용 대상 예시]
        ///   기사형 돌진, 드론형 급강하, 골렘형 구르기
        /// </summary>
        Dash,

        /// <summary>
        /// 점프 봉인.
        /// 적의 Jump / 공중 이동 행동을 차단.
        /// 지상 고정 효과. 공중에 있는 적에게 적용 시 낙하 유도.
        ///
        /// [적용 대상 예시]
        ///   드론형 상승, 기사형 점프 공격
        /// </summary>
        Jump,

        /// <summary>
        /// 원거리 공격 봉인.
        /// 적의 투사체 발사 / 원거리 공격 행동을 차단.
        /// EnemyAttackBase 의 ExecuteAttack() 직전에 체크.
        ///
        /// [적용 대상 예시]
        ///   궁수형 화살, 드론형 레이저, 마법사형 마법구
        /// </summary>
        Ranged,

        /// <summary>
        /// 방어 봉인.
        /// 적의 방어 / 가드 행동을 차단.
        /// 기사형 방패 막기, 거북이형 웅크리기 등에 적용.
        /// 봉인 중에는 정면 피격도 데미지 적용.
        ///
        /// [적용 대상 예시]
        ///   기사형 방패, 골렘형 돌 껍질, 거북이형 등껍질
        /// </summary>
        Guard,

        /// <summary>
        /// 이동 봉인.
        /// 적의 Patrol / Chase 이동 전체를 차단.
        /// 완전 정지 효과. 가장 강력한 봉인.
        /// SealDataSO.duration 을 짧게 설정 권장 (밸런스).
        ///
        /// [적용 대상 예시]
        ///   모든 적 타입에 공통 적용 가능
        /// </summary>
        Move,

        /// <summary>
        /// 공격 봉인.
        /// 적의 모든 공격 행동(근접 + 원거리)을 차단.
        /// Ranged 봉인과 달리 근접 공격도 포함.
        ///
        /// [적용 대상 예시]
        ///   모든 적 타입 공통. 자물쇠 해제 시간 확보에 유용.
        /// </summary>
        Attack,
    }
}